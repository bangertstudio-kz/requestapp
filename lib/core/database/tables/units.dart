///
/// Порядок — часть контракта, а не оформление: `unit_mapping.dart` в слое
/// data переводит идентификатор в доменный `ItemUnit` по этому правилу,
/// а `unit_mapping_test` следит, чтобы список и перечисление не разъехались.
