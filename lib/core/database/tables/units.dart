import 'package:drift/drift.dart';

/// Справочник единиц измерения.
///
/// Отдельная таблица, а не текстовая колонка в позиции: единица — свойство
/// материала из прайса, и набор допустимых значений задаётся один раз.
/// Строка «м.п.», записанная в каждый из 326 материалов, рано или поздно
/// встретилась бы в виде «м.п» — и половина трубы считалась бы в другом.
@DataClassName('UnitRow')
class Units extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Код из прайса: `шт.`, `м.п.`, `комплект`.
  TextColumn get code => text()();
}

