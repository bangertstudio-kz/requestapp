/// Маркер аргументов запроса — фильтры, поисковая строка, идентификаторы.
///
/// Свой класс параметров заводится на каждый запрос, даже пустой: это место,
/// куда лягут фильтры, когда они появятся, и подпись, по которой видно, что
/// именно запрашивают. Запрос без аргументов параметризуется `Null`
/// и вызывается как `request(null)`.
abstract class Params {
  const Params();
}

