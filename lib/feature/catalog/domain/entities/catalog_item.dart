import 'item_unit.dart';

/// Материал справочника.
///
/// Имя `CatalogItem`, а не `Item`: последнее слишком общее, чтобы читаться
/// в чужом файле без импорта.
class CatalogItem {
  const CatalogItem({
    required this.id,
    required this.name,
    required this.unit,
    this.path = const [],
  });

  final String id;
  final String name;

  /// Единица приходит из справочника и в заявке не редактируется: одна и та
  /// же труба не может считаться в штуках у одного прораба и в метрах
  /// у другого.
  final ItemUnit unit;

  /// Названия категорий от корня до той, в которой лежит материал.
  ///
  /// Список, а не пара строк: дерево любой глубины, и «Канализация → Труба →
  /// Чугунная» так же законно, как «Расходный материал» одним звеном. Строки,
  /// а не ссылки: карточка показывает путь, не поднимая весь справочник.
  ///
  /// Пустой — путь ещё не собран: так приезжает материал из разобранного
  /// прайса, где место задано вложенностью, а не названиями.
  final List<String> path;
}
