/// Идентификатор единицы в таблице `unit`: позиция в [ItemUnit] плюс один.
///
/// Связь держится на порядке, а не на совпадении строк, потому что код
/// единицы — значение из прайса («м.п.»), и опечатка в нём не должна
/// превращать метры в штуки. За тем, что порядок [unitCodes] и порядок
/// [ItemUnit] совпадают, следит `unit_mapping_test`.
int unitIdOf(ItemUnit unit) => unit.index + 1;

/// Код единицы словом: `шт.`, `м.п.`, `комплект`.
///
/// Тот же словарь, что лежит в базе: единица в отправленном поставщику
/// файле и единица в справочнике обязаны совпадать буква в букву, иначе
/// расхождение находят при приёмке.
String unitCodeOf(ItemUnit unit) => unitCodes[unit.index];

/// Обратный перевод. Идентификатор вне словаря — испорченная база:
/// словарь засевается один раз и не редактируется. Позиция всё равно
/// показывается, просто в штуках: ронять весь справочник из-за одной
/// строки — цена выше, чем неверная подпись у неё же.
ItemUnit unitFromId(int id) {
  final index = id - 1;
  if (index < 0 || index >= ItemUnit.values.length) return ItemUnit.piece;
  return ItemUnit.values[index];
}
