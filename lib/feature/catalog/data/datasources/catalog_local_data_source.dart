import '../../domain/entities/catalog_category.dart';
import '../../domain/entities/catalog_item.dart';
import '../../domain/entities/import_row.dart';
import '../../domain/entities/item_draft.dart';

/// Справочник в локальном хранилище.
///
/// Отдельно от репозитория, потому что у репозитория есть работа помимо
/// хранения: разобрать прайс, посчитать, что даст импорт, решить, что
/// показать при отказе. Здесь — только чтение и запись, и ничего, что
/// нужно было бы менять при смене формата прайса.
///
/// Идентификаторы — строки, как в домене. Что внутри они целые, знает
/// только реализация: маршрут `/catalog/c12` не обязан сообщать экрану,
/// чем считает свои ключи SQLite.
abstract interface class CatalogLocalDataSource {
  /// Всё дерево любой глубины вместе с материалами.
  /// Пустые ветки приезжают тоже — в них добавляют материалы.
  Future<List<CatalogCategory>> categories();

  /// Плоский поиск по названиям материалов. Регистр и лишние пробелы
  /// не важны; пустой запрос — пустой список, а не весь справочник.
  Future<List<CatalogItem>> searchItems(String query);

  /// Создаёт категорию, переименовывает её или переносит.
  ///
  /// `id == null` — создание, `parentId == null` — верхний уровень.
  /// Бросает [DescribedFailure], если родитель — сама категория или кто-то
  /// из её потомков: такая ветка исчезает из дерева, оставаясь в базе.
  Future<void> saveCategory({
    String? id,
    required String name,
    required String? parentId,
  });

  /// Удаляет категорию вместе со всем поддеревом и его материалами.
  /// Позиции заявок, ссылавшиеся на эти материалы, остаются без ссылки.
  Future<void> deleteCategory(String id);

  /// Создаёт материал, переименовывает его или переносит в другую
  /// категорию — в форме это один и тот же набор полей.
  Future<void> saveItem(ItemDraft draft);

  Future<void> deleteItem(String id);

  /// Заменяет справочник целиком одной транзакцией и возвращает число
  /// записанных материалов. Наполовину заменённый справочник — состояние,
  /// в котором приложение не должно оказываться даже на секунду.
  Future<int> replaceCatalog(List<CatalogCategory> categories);

  /// Вливает разобранные строки в категорию. `categoryId == null` — в корень.
  ///
  /// Недостающие ветки создаются по пути строки. Материал с таким же
  /// названием в той же ветке обновляется, остальные добавляются: импорт
  /// дополняет справочник, а не переписывает чужую работу. Возвращает,
  /// сколько материалов записано.
  ///
  /// Совпадение ищется внутри ветки, а не по всему справочнику: «Труба ⌀25»
  /// в ППР и в металлопластике — разные материалы.
  Future<int> importItems(String? categoryId, List<ImportRow> rows);
}
