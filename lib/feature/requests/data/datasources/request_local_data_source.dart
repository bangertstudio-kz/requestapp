/// Заявки и папки в локальном хранилище.
///
/// Вместо `save` и `send` — [markSaved] и [markSent]: записать файлы
/// на устройство и отправить письмо хранилище не умеет и уметь не должно.
/// Файлы пишет репозиторий, сюда приходит уже случившийся факт с его
/// временем. Иначе датасорс пришлось бы звать «репозиторием номер два».
abstract interface class RequestLocalDataSource {
  /// Заявки, прошедшие папку, фильтр и поиск, плюс общее число заявок.
  ///
  /// Отбор идёт в SQL, включая поиск по названиям материалов внутри заявки:
  /// поднимать все заявки со всеми позициями, чтобы отсеять их в Dart, —
  /// это вся база в памяти ради одного экрана.
  Future<RequestList> list(RequestsParams params);

  /// Одна заявка вместе с позициями. Бросает [DescribedFailure], если её
  /// нет: экран детали открывают по ссылке, и пустая заявка вместо
  /// удалённой была бы враньём.
  Future<MaterialRequest> byId(String id);

  /// Новая пустая заявка в «Черновике».
  ///
  /// Название и дату задаёт вызывающий: как называется заявка по умолчанию
  /// и что считать «сегодня» — решение домена, а не хранилища, и именно
  /// его подменяет тест, чтобы не зависеть от системных часов.
  Future<MaterialRequest> create({
    String? folderId,
    required String name,
    required DateTime createdAt,
  });

  /// Переименование и правка позиций. Возвращает заявку в «Черновик»
  /// и снимает отметку о сохранении: файлы на устройстве после правки
  /// описывают не то, что теперь в заявке. Отметка об отправке остаётся —
  /// заявку правда отправляли, и это факт, а не состояние.
  ///
  /// Позиции сверяются по идентификатору: существующие правятся на месте,
  /// новые вставляются, пропавшие удаляются. Не «удалить все и записать
  /// заново» — иначе у каждой позиции при каждой правке менялся бы
  /// идентификатор, и ссылка на строку жила бы до первого сохранения.
  Future<MaterialRequest> update(MaterialRequest request);

  /// Переносит заявку в папку. `folderId == null` — вне папок.
  ///
  /// Отдельно от [update], потому что папка — не часть документа: файлы,
  /// уже лежащие на устройстве, после переноса описывают ту же заявку.
  /// Сбрасывать здесь статус значило бы требовать сохранить заново из-за
  /// того, что заявку положили в другую папку.
  Future<MaterialRequest> moveToFolder(String id, String? folderId);

  Future<void> delete(String id);

  /// Отмечает, что файлы легли на устройство в [savedAt].
  Future<MaterialRequest> markSaved(String id, DateTime savedAt);

  /// Отмечает отправку и запоминает формат вложения: следующая отправка
  /// предлагает тот же, которым отправляли в прошлый раз.
  Future<MaterialRequest> markSent(
    String id,
    SendFormat format,
    DateTime sentAt,
  );

  /// Папки вместе с числом заявок в каждой. Счётчик считает хранилище:
  /// по загруженному списку можно посчитать только загруженное, а список
  /// приезжает уже отфильтрованным.
  Future<List<RequestFolder>> folders();

  Future<RequestFolder> createFolder(String name);
}
